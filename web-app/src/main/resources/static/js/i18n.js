// Client-side i18n localization core engine
function applyTranslations() {
    const lang = localStorage.getItem("canineai-lang") || "en";
    
    // Toggle RTL layout for Arabic
    if (lang === "ar") {
        document.documentElement.setAttribute("dir", "rtl");
        document.documentElement.classList.add("rtl-layout");
    } else {
        document.documentElement.setAttribute("dir", "ltr");
        document.documentElement.classList.remove("rtl-layout");
    }

    // Apply translations to all DOM elements decorated with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                if (el.placeholder) {
                    el.placeholder = translations[lang][key];
                }
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    // Custom Font-sizing adjustments
    const fontSize = localStorage.getItem("canineai-font-size") || "medium";
    document.documentElement.classList.remove("font-size-sm", "font-size-md", "font-size-lg");
    if (fontSize === "small") {
        document.documentElement.classList.add("font-size-sm");
    } else if (fontSize === "large") {
        document.documentElement.classList.add("font-size-lg");
    } else {
        document.documentElement.classList.add("font-size-md");
    }

    // Custom Animation Preferences
    const animations = localStorage.getItem("canineai-animations") || "on";
    if (animations === "off") {
        document.documentElement.classList.add("no-animations");
    } else {
        document.documentElement.classList.remove("no-animations");
    }
}

// Attach event listener for immediate DOM execution
document.addEventListener("DOMContentLoaded", applyTranslations);
window.addEventListener("i18n-update", applyTranslations);
